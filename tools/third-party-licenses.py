"""Write THIRD-PARTY-LICENSES.md: every Rust crate that ends up in Washi's binaries, with its
version, its SPDX licence expression and the licence texts the crates ship, deduplicated.

    python3 tools/third-party-licenses.py            # write THIRD-PARTY-LICENSES.md
    python3 tools/third-party-licenses.py --check    # exit 1 when the file is out of date

The crate list comes from `cargo metadata` (Linux target, normal and build dependencies; dev
dependencies are not shipped and are left out), the texts from the crate sources that cargo has
unpacked into its registry (CARGO_HOME, default ~/.cargo/registry/src). Run `cargo fetch --locked`
first when the sources are not there. Standard library only.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-LICENSES.md"
TARGET = "x86_64-unknown-linux-gnu"
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|unlicen[cs]e|notice|copyright)([-_. ].*)?$", re.I)
# Crates whose `license` field is empty and which describe their licence in `license-file`.
HEADER = """\
# Third-party licences

Washi itself is licensed under the GNU General Public License, version 2 or (at your option) any
later version (see `LICENSE`). This file lists the Rust crates that are compiled into the Washi
binaries (`washi`, `washid`, `washi-app`) or used to build them, with the licence texts they ship.

**Binaries are distributed under the terms of the GPL-3.0-or-later.** Some of the crates below
are licensed under the Apache License 2.0 only, which is compatible with version 3 of the GPL but
not with version 2 alone. Washi's own code is "GPL-2.0-or-later", so the combination can be
distributed under GPL-3.0-or-later. The one MPL-2.0 crate is compatible with the GPL through the
licence's secondary-licence clause.

The text of the GPL-3.0-or-later is in `LICENSES/GPL-3.0-or-later.txt`.

The Qt 6 libraries, KDE Frameworks (KI18n), poppler and the other system libraries Washi uses are
not part of this file: they are loaded from the system (or from the Flatpak runtime) and come with
their own licences (LGPL / GPL).

Generated by `tools/third-party-licenses.py` from `Cargo.lock`; do not edit by hand.
"""


def run_metadata(offline: bool) -> dict:
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET]
    if offline:
        cmd.append("--offline")
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"cargo metadata failed:\n{out.stderr}")
    return json.loads(out.stdout)


def reachable(meta: dict, kinds: set) -> set:
    """Package ids reachable from the workspace members over edges whose kind is in `kinds`
    (None = normal dependency)."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen = set(meta["workspace_members"])
    todo = list(seen)
    while todo:
        node = nodes.get(todo.pop())
        if not node:
            continue
        for dep in node["deps"]:
            if any(k["kind"] in kinds for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return seen


def license_files(pkg: dict) -> list:
    root = Path(pkg["manifest_path"]).parent
    found = []
    if not root.is_dir():
        return found
    for path in sorted(root.iterdir()):
        if path.is_file() and LICENSE_FILE.match(path.name):
            found.append(path)
        elif path.is_dir() and path.name.upper() in ("LICENSES", "LICENCES"):
            # REUSE layout: LICENSES/<SPDX id>.txt
            found.extend(sorted(p for p in path.iterdir() if p.is_file()))
    lf = pkg.get("license_file")
    if lf and (root / lf).is_file() and (root / lf) not in found:
        found.append(root / lf)
    return found


def read_text(path: Path) -> str:
    text = path.read_text("utf-8", "replace").replace("\r\n", "\n").strip("\n")
    return text.rstrip() + "\n"


def classify(text: str) -> str:
    low = text.lower()
    if "apache license" in low and "version 2.0" in low:
        return "Apache License 2.0"
    if "mozilla public license" in low:
        return "Mozilla Public License 2.0"
    if "permission is hereby granted, free of charge" in low:
        return "MIT licence"
    if "redistribution and use in source and binary forms" in low:
        return "BSD 3-Clause licence" if "neither the name" in low else "BSD 2-Clause licence"
    if "unencumbered" in low:
        return "Unlicense"
    if "altered source versions" in low:
        return "zlib licence"
    if "unicode license" in low or ("unicode" in low and "terms of use" in low):
        return "Unicode licence"
    if "permission to use, copy, modify, and/or distribute" in low:
        return "ISC / 0BSD style licence"
    first = next((ln.strip() for ln in text.splitlines() if ln.strip()), "licence")
    return first[:60]


def copyright_line(text: str) -> str:
    for ln in text.splitlines():
        if re.search(r"copyright|\(c\)|©", ln, re.I) and "yyyy" not in ln.lower():
            return ln.strip()[:100]
    return ""


def group_key(text: str):
    """Apache-2.0 texts differ only in the notice of the appendix: group them by the terms."""
    if classify(text) == "Apache License 2.0":
        body = text.split("END OF TERMS AND CONDITIONS")[0]
        key = hashlib.sha256(re.sub(r"\s+", " ", body).encode()).hexdigest()
        return "apache:" + key, body.rstrip() + "\n\nEND OF TERMS AND CONDITIONS\n"
    return hashlib.sha256(text.encode()).hexdigest(), text


def build() -> str:
    meta = run_metadata(offline=True)
    packages = {p["id"]: p for p in meta["packages"]}
    members = set(meta["workspace_members"])
    normal = reachable(meta, {None})
    with_build = reachable(meta, {None, "build"})
    rows = []
    for pid in sorted(with_build - members, key=lambda i: (packages[i]["name"], packages[i]["version"])):
        pkg = packages[pid]
        rows.append((pkg, pid in normal))

    texts = {}  # sha256 -> text
    users = defaultdict(list)  # sha256 -> [(crate, version, filename)]
    missing = []
    for pkg, _ in rows:
        files = license_files(pkg)
        if not files:
            missing.append(pkg)
        for f in files:
            text = read_text(f)
            digest, shown = group_key(text)
            texts.setdefault(digest, shown)
            users[digest].append((pkg["name"], pkg["version"], f.name, copyright_line(text)))

    spdx_count = defaultdict(int)
    for pkg, _ in rows:
        spdx_count[pkg.get("license") or "(none declared)"] += 1

    out = [HEADER]
    out.append(f"## Summary\n\n{len(rows)} crates (normal and build dependencies, Linux target).\n")
    out.append("| Licence (SPDX expression) | Crates |\n|---|---|")
    for expr, n in sorted(spdx_count.items(), key=lambda kv: (-kv[1], kv[0])):
        out.append(f"| {expr} | {n} |")
    out.append("")
    out.append("## Crates\n")
    out.append("`build` marks crates that only run while building and are not part of the binaries.\n")
    out.append("| Crate | Version | Licence | |\n|---|---|---|---|")
    for pkg, is_normal in rows:
        tag = "" if is_normal else "build"
        out.append(f"| {pkg['name']} | {pkg['version']} | {pkg.get('license') or '(see licence file)'} | {tag} |")
    out.append("")
    if missing:
        out.append("Crates that ship no licence file (the licence named above applies; the text is the "
                   "standard one): " + ", ".join(f"{p['name']} {p['version']}" for p in missing) + ".\n")
    out.append("## Licence texts\n")
    out.append("Identical texts are printed once, followed by the crates that ship them.\n")
    order = sorted(texts, key=lambda d: (classify(texts[d]), -len(users[d]), users[d][0][0], d))
    for n, digest in enumerate(order, 1):
        names = sorted({f"{c} {v}" for c, v, _, _ in users[digest]})
        kind = classify(texts[digest])
        notice = copyright_line(texts[digest]) if kind != "Apache License 2.0" else ""
        out.append(f"### {n}. {kind}" + (f" - {notice}" if notice else "") + "\n")
        out.append("Used by: " + ", ".join(names) + "\n")
        if kind == "Apache License 2.0":
            notices = sorted({c for _, _, _, c in users[digest] if c})
            if notices:
                out.append("Copyright notices given by the crates: " + "; ".join(notices) + "\n")
        fence = "~~~~" if "```" in texts[digest] else "```"
        out.append(fence + "text\n" + texts[digest].rstrip("\n") + "\n" + fence + "\n")
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when THIRD-PARTY-LICENSES.md is stale")
    args = ap.parse_args()
    os.chdir(ROOT)
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text("utf-8") != text:
            print("THIRD-PARTY-LICENSES.md is out of date: run tools/third-party-licenses.py", file=sys.stderr)
            return 1
        print("THIRD-PARTY-LICENSES.md is up to date")
        return 0
    OUT.write_text(text, "utf-8")
    print(f"wrote {OUT} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
